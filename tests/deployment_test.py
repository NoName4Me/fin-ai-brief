"""Exercise real packaging/deployment scripts with Docker I/O simulated, no live services."""
import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess
import tarfile
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('deploy_config', ROOT / 'deploy/config.py')
config = importlib.util.module_from_spec(spec)
spec.loader.exec_module(config)

DOCKER = '''#!/usr/bin/env python3
import json, os, pathlib, sys
a=sys.argv[1:]
with open(os.environ['DOCKER_LOG'],'a') as f: f.write(json.dumps(a)+'\\n')
if a[:2]==['image','inspect']:
    if os.environ.get('MISSING_IMAGE') and os.environ['MISSING_IMAGE'] in a: sys.exit(1)
    if '--format' in a: print('sha256:'+'a'*64)
elif a[:2]==['image','save']:
    pathlib.Path(a[a.index('-o')+1]).write_text(json.dumps(a[a.index('-o')+2:]))
elif a[:1]==['info']: print(os.environ.get('DOCKER_PLATFORM','linux/x86_64'))
elif a[:1]==['inspect']: print('fin-ai-brief-postgres:17-existing')
elif a[:1]==['compose']:
    if 'run' in a and 'migrate' in a and os.environ.get('FAIL_MIGRATE'): sys.exit(1)
    if 'pg_dump' in a: print('valid simulated database backup')
    elif 'pg_restore' in a: sys.stdin.read(); print('valid simulated TOC')
    elif 'ps' in a and '-q' in a: print('existing-db-container')
'''


class DeploymentTest(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        for name in ['scripts', 'deploy', 'docs']:
            shutil.copytree(ROOT / name, self.root / name,
                            ignore=shutil.ignore_patterns('.env', '.state', 'backups', '__pycache__'))
        self.bin = self.root / 'bin'
        self.bin.mkdir()
        (self.bin / 'docker').write_text(DOCKER)
        (self.bin / 'git').write_text("#!/usr/bin/env python3\nimport json, os, pathlib, sys\na=sys.argv[1:]\nmarker=pathlib.Path(os.environ['GIT_MARKER'])\nwith open(os.environ['GIT_LOG'],'a') as f: f.write(json.dumps(a)+'\\n')\nif a[0]=='status':\n    if os.environ.get('GIT_DIRTY') and not marker.exists(): print(' M src/example.ts')\nelif a[0]=='commit':\n    if os.environ.get('FAIL_COMMIT'): sys.exit(1)\n    marker.touch()\nelif a[0]=='rev-parse': print('abc12' if '--short=5' in a else 'a'*40)\n")
        # macOS lacks flock; this fixture tests deployment ordering rather than OS locking.
        (self.bin / 'flock').write_text('#!/bin/sh\nexit 0\n')
        for file in self.bin.iterdir():
            file.chmod(0o755)
        self.log = self.root / 'docker.log'
        self.env = {**os.environ, 'PATH': str(self.bin) + os.pathsep + os.environ['PATH'],
                    'DOCKER_LOG': str(self.log), 'GIT_LOG': str(self.root / 'git.log'),
                    'GIT_MARKER': str(self.root / 'git-committed')}
        for key in ['APP_VERSION', 'POSTGRES_IMAGE', 'NGINX_IMAGE', 'DEPLOY_ENV_FILE',
                    'DEPLOY_STATE_DIR', 'DEPLOY_BACKUP_DIR', 'DEPLOY_PROJECT']:
            self.env.pop(key, None)

    def command(self, script, *args, ok=True):
        result = subprocess.run(['bash', str(self.root / 'scripts' / script), *args],
                                cwd=self.root, env=self.env, capture_output=True, text=True)
        if ok:
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        else:
            self.assertNotEqual(result.returncode, 0, result.stdout + result.stderr)
        return result

    def calls(self):
        return [json.loads(line) for line in self.log.read_text().splitlines()]

    def package(self, full=False):
        (self.root / '.env').write_text('PRIVATE_LOCAL_SECRET=never-package-this\n')
        self.command('package-release.sh', *(['--full'] if full else []))
        path = next((self.root / '.data/releases').glob('*.tar.gz'))
        with tarfile.open(path) as archive:
            members = archive.getnames()
            self.assertNotIn('./deploy/.env', members)
            self.assertNotIn('./.env', members)
            # Packages are generated by this test from trusted fixture files.
            archive.extractall(self.root, filter='data')
        return config.release(self.root, verify=True)

    def initialize(self, installed=True):
        self.command('deploy.sh', 'init', '80', '198.51.100.1/32')
        env_file = self.root / 'deploy/.env'
        env_file.write_text(env_file.read_text().replace('SITE_URL=\n',
                                                       'SITE_URL=http://203.0.113.1\n'))
        env_file.write_text(env_file.read_text().replace('JIANYU_COOKIE=\n',
                                                       'JIANYU_COOKIE=existing-cookie\n'))
        if installed:
            state = self.root / 'deploy/.state'
            (state / 'current').write_text('old-version\n')
            (state / 'postgres-image').write_text('fin-ai-brief-postgres:17-existing\n')
            (state / 'nginx-image').write_text('fin-ai-brief-nginx:existing\n')
        return env_file.read_bytes()

    def test_package_name_and_full_commit_metadata(self):
        value = self.package()
        name = next((self.root / '.data/releases').glob('*.tar.gz')).name
        self.assertRegex(name, r'^fin-ai-brief-update-amd64-abc12-\d{8}-\d{6}\.tar\.gz$')
        self.assertEqual(value['git_commit'], 'a' * 40)
        calls = [json.loads(line) for line in (self.root / 'git.log').read_text().splitlines()]
        self.assertFalse(any(call[0] in ['add', 'commit'] for call in calls))

    def test_dirty_package_requires_manual_commit(self):
        self.env['GIT_DIRTY'] = '1'
        result = self.command('package-release.sh', ok=False)
        self.assertIn('请先手动提交', result.stderr)
        self.assertFalse(self.log.exists())
        calls = [json.loads(line) for line in (self.root / 'git.log').read_text().splitlines()]
        self.assertFalse(any(call[0] in ['add', 'commit', 'push'] for call in calls))

    def test_update_contains_only_application_images_and_no_private_env(self):
        value = self.package()
        self.assertEqual(value['mode'], 'update')
        saved = json.loads((self.root / 'release/images.tar').read_text())
        self.assertEqual(len(saved), 2)
        self.assertTrue(saved[0].startswith('fin-ai-brief-web:'))
        self.assertTrue(saved[1].startswith('fin-ai-brief-worker:'))
        self.assertFalse(any(c[0] == 'pull' or 'postgres:17-bookworm' in c or
                             'nginx:stable-alpine' in c for c in self.calls()))

    def test_full_package_supports_new_machine(self):
        value = self.package(full=True)
        self.assertEqual(value['mode'], 'full')
        self.assertEqual(len(json.loads((self.root / 'release/images.tar').read_text())), 4)
        self.initialize(installed=False)
        self.command('deploy.sh', 'deploy')
        self.assertTrue((self.root / 'deploy/.state/current').exists())

    def test_legacy_full_package_still_loads(self):
        self.package(full=True)
        path = self.root / 'release/manifest.json'
        value = json.loads(path.read_text())
        value.pop('mode')
        path.write_text(json.dumps(value))
        self.assertEqual(config.release(self.root, verify=True)['mode'], 'full')
        self.initialize(installed=False)
        self.command('deploy.sh', 'load')

    def test_update_preserves_env_base_images_and_database_container(self):
        original = self.initialize()
        value = self.package()
        self.log.write_text('')
        self.command('deploy.sh', 'deploy')
        self.assertEqual((self.root / 'deploy/.env').read_bytes(), original)
        state = self.root / 'deploy/.state'
        self.assertEqual((state / 'current').read_text().strip(), value['version'])
        self.assertEqual((state / 'postgres-image').read_text().strip(),
                         'fin-ai-brief-postgres:17-existing')
        self.assertEqual((state / 'nginx-image').read_text().strip(),
                         'fin-ai-brief-nginx:existing')
        calls = self.calls()
        stops = [c[c.index('stop')+1:] for c in calls if 'stop' in c]
        self.assertEqual(stops, [['web', 'worker']])
        db_start = next(c for c in calls if 'up' in c and c[-1] == 'db')
        self.assertIn('--no-recreate', db_start)
        nginx_start = next(c for c in calls if 'up' in c and c[-1] == 'nginx')
        self.assertNotIn('--force-recreate', nginx_start)
        self.assertTrue(any('nginx -s reload' in c[-1] for c in calls))
        self.assertEqual(len(list((self.root / 'deploy/backups').glob('*.dump'))), 1)
        backup_index = next(i for i, c in enumerate(calls) if 'pg_dump' in c)
        migrate_index = next(i for i, c in enumerate(calls) if 'run' in c and 'migrate' in c)
        web_index = next(i for i, c in enumerate(calls) if 'up' in c and 'web' in c)
        self.assertLess(backup_index, migrate_index)
        self.assertLess(migrate_index, web_index)

    def test_update_on_new_machine_fails_before_stopping_services(self):
        self.package()
        self.initialize(installed=False)
        self.log.write_text('')
        result = self.command('deploy.sh', 'deploy', ok=False)
        self.assertIn('--full', result.stderr)
        self.assertFalse(self.calls())

    def test_missing_base_image_fails_before_stopping_services(self):
        self.package()
        self.initialize()
        self.log.write_text('')
        self.env['MISSING_IMAGE'] = 'fin-ai-brief-nginx:existing'
        self.command('deploy.sh', 'deploy', ok=False)
        self.assertFalse(any('stop' in c for c in self.calls()))
        self.assertEqual((self.root / 'deploy/.state/current').read_text(), 'old-version\n')

    def test_failed_migration_does_not_record_success_or_start_new_apps(self):
        self.package()
        self.initialize()
        self.log.write_text('')
        self.env['FAIL_MIGRATE'] = '1'
        self.command('deploy.sh', 'deploy', ok=False)
        self.assertEqual((self.root / 'deploy/.state/current').read_text(), 'old-version\n')
        self.assertFalse(any('up' in c and 'web' in c for c in self.calls()))
        self.assertTrue(list((self.root / 'deploy/backups').glob('*.dump')))

    def test_tampered_package_is_rejected_before_image_load(self):
        self.package()
        self.initialize()
        (self.root / 'release/images.tar').write_text('tampered')
        self.log.write_text('')
        self.command('deploy.sh', 'deploy', ok=False)
        self.assertFalse(any('load' in c or 'stop' in c for c in self.calls()))

    def test_unknown_mode_and_update_infra_overrides_are_rejected(self):
        self.package()
        path = self.root / 'release/manifest.json'
        value = json.loads(path.read_text())
        for fields in [{'mode': 'unknown'}, {'nginx_image': 'fin-ai-brief-nginx:other'}]:
            path.write_text(json.dumps({**value, **fields}))
            with self.assertRaises(ValueError):
                config.release(self.root)

    def test_wrong_architecture_fails_before_loading_or_stopping(self):
        self.package()
        self.initialize()
        self.log.write_text('')
        self.env['DOCKER_PLATFORM'] = 'linux/aarch64'
        self.command('deploy.sh', 'deploy', ok=False)
        self.assertFalse(any('load' in c or 'stop' in c for c in self.calls()))

    def test_arm_update_package_records_platform_without_base_images(self):
        self.command('package-release.sh', '--platform', 'linux/arm64')
        path = next((self.root / '.data/releases').glob('fin-ai-brief-update-arm64-*.tar.gz'))
        with tarfile.open(path) as archive:
            value = json.loads(archive.extractfile('./release/manifest.json').read())
            images = json.loads(archive.extractfile('./release/images.tar').read())
        self.assertEqual(value['platform'], 'linux/arm64')
        self.assertEqual(len(images), 2)


if __name__ == '__main__':
    unittest.main()
